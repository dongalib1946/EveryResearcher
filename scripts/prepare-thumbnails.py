"""Build local thumbnails from the public archive API JSON.
Usage: python3 scripts/prepare-thumbnails.py /path/to/archive.json
Requires Pillow; downloaded originals stay in the system temporary directory.
"""
import concurrent.futures, hashlib, json, pathlib, subprocess, sys, tempfile
from urllib.parse import urlparse, parse_qs
from PIL import Image, ImageOps

root = pathlib.Path(__file__).resolve().parents[1]
out = root / 'assets/images/thumbnails'
out.mkdir(parents=True, exist_ok=True)
cache = pathlib.Path(tempfile.gettempdir()) / 'everyresearcher-posters'
cache.mkdir(exist_ok=True)
rows = json.loads(pathlib.Path(sys.argv[1]).read_text())['winners']
ids = set()
for row in rows:
    if str(row.get('published')).lower() != 'true':
        continue
    url = urlparse(row.get('profileUrl', ''))
    if url.hostname != 'drive.google.com':
        continue
    file_id = parse_qs(url.query).get('id', [''])[0]
    if not file_id and '/file/d/' in url.path:
        file_id = url.path.split('/file/d/')[1].split('/')[0]
    if file_id:
        ids.add(file_id)

def generate(file_id):
    source = cache / (file_id + '.png')
    if not source.exists():
        subprocess.run(['curl', '-fLs', '--retry', '2', '--max-time', '90',
                        'https://drive.google.com/uc?export=download&id=' + file_id,
                        '-o', str(source)], check=True)
    with Image.open(source) as raw:
        image = ImageOps.exif_transpose(raw).convert('RGB')
        digest = hashlib.sha256(source.read_bytes()).hexdigest()[:12]
        files = []
        for width in (480, 960, 1440):
            actual = min(width, image.width)
            height = round(image.height * actual / image.width)
            name = f'{digest}-{actual}.webp'
            image.resize((actual, height), Image.Resampling.LANCZOS).save(out / name, 'WEBP', quality=82, method=6)
            files.append({'file': name, 'width': actual})
        return file_id, {'width': image.width, 'height': image.height, 'sources': files}, source.stat().st_size

with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    results = list(pool.map(generate, sorted(ids)))
manifest = {key: data for key, data, _ in results}
(root / 'assets/js/thumbnail-manifest.js').write_text('// Generated by scripts/prepare-thumbnails.py; keyed by original Google Drive image ID.\nexport const THUMBNAILS = ' + json.dumps(manifest, indent=2) + ';\n')
print(json.dumps({'works': len(results), 'originalBytes': sum(size for _, _, size in results),
                  'webpBytes': {width: sum((out / d['sources'][i]['file']).stat().st_size for _, d, _ in results) for i, width in enumerate((480,960,1440))}}, indent=2))
